#!/usr/bin/env python3
"""Expose the inherited test functions to Go's test runner during migration."""
from pathlib import Path
import re
for directory in Path('src/go/kame').rglob('test'):
    groups={}
    package=None
    for source in sorted(directory.glob('*.go')):
        if source.name.endswith('_test.go'):continue
        text=source.read_text()
        package=re.search(r'^package (\w+)',text,re.M).group(1)
        tags='linux' if text.startswith('//go:build linux') else ''
        groups.setdefault(tags,[]).extend(re.findall(r'^func (Test\w+)\(t \*testing.T\)',text,re.M))
    for tag,names in groups.items():
        if not names:continue
        filename='go_tests_'+tag+'_test.go' if tag else 'go_tests_test.go'
        header='//go:build '+tag+'\n\n' if tag else ''
        text=header+'// Code generated by tools/go-tests.py; DO NOT EDIT.\npackage '+package+'\n\nimport ("testing"; legacy "kame/internal/testing")\n\n'
        text+='func TestGoSuite(t *testing.T) {\n' if not tag else 'func TestGoLinuxSuite(t *testing.T) {\n'
        for name in sorted(names):
            text+='t.Run("'+name[4:]+'", func(t *testing.T){'+name+'(legacy.Wrap(t))})\n'
        text+='}\n'
        (directory/filename).write_text(text)
