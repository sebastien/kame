import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {WASI} from 'node:wasi';
const wasi=new WASI({version:'preview1',returnOnExit:true});
const bytes=await readFile(process.argv[2]??'build/wasm/kame.wasm');
const {instance}=await WebAssembly.instantiate(bytes,{wasi_snapshot_preview1:wasi.wasiImport});
wasi.initialize(instance);
const e=instance.exports;
assert.equal(e.kame_wasm_abi_version(),1);
function buffer(text){const data=new TextEncoder().encode(text);const pointer=e.kame_wasm_alloc(data.length||1,8);new Uint8Array(e.memory.buffer,pointer,data.length).set(data);return {pointer,length:data.length,allocated:data.length||1};}
const source=buffer('(join ":" ["left" "right"])');
const output=e.kame_wasm_alloc(4096,8);
const length=e.kame_wasm_alloc(4,4);
assert.equal(e.kame_wasm_eval_pure(source.pointer,source.length,output,4096,length),0);
const size=new DataView(e.memory.buffer).getUint32(length,true);
assert.equal(new TextDecoder().decode(new Uint8Array(e.memory.buffer,output,size)),'"left:right"');
assert.equal(e.kame_wasm_eval_pure(0xfffffff0,32,output,4096,length),4);
const handle=e.kame_wasm_instance_create();
assert.equal(e.kame_wasm_result_diagnostic(handle,output,4096,length),0);
assert.equal(new DataView(e.memory.buffer).getUint32(length,true),0);
const args=buffer('--help');
const command=buffer('@presentation');
assert.equal(e.kame_wasm_cli(handle,command.pointer,command.length,args.pointer,args.length,output,4096,length),0);
const cli=JSON.parse(new TextDecoder().decode(new Uint8Array(e.memory.buffer,output,new DataView(e.memory.buffer).getUint32(length,true))));
assert.equal(cli.earlyAction,'help');
assert.equal(e.kame_wasm_source_compile(handle,0,0),0);
assert.equal(e.kame_wasm_expression_begin(handle,source.pointer,source.length),0);
for(let n=0;n<100;n++){const status=e.kame_wasm_step(handle);if(status===2)break;assert.equal(status,0);assert(n<99,'expression did not complete');}
assert.equal(e.kame_wasm_result_copy(handle,output,4096,length),0);
assert.equal(new TextDecoder().decode(new Uint8Array(e.memory.buffer,output,new DataView(e.memory.buffer).getUint32(length,true))), '"left:right"');
assert.equal(e.kame_wasm_instance_free(handle),0);
assert.equal(e.kame_wasm_instance_free(handle),1);
const hosted=e.kame_wasm_instance_create();
const read=buffer('(read "./input")');
const content=buffer('backend bytes');
assert.equal(e.kame_wasm_source_compile(hosted,0,0),0);
assert.equal(e.kame_wasm_expression_begin(hosted,read.pointer,read.length),0);
let needed=false;
for(let n=0;n<100;n++){const status=e.kame_wasm_step(hosted);if(status===1){needed=true;break;}assert.equal(status,0);}
assert(needed,'read did not request host work');
assert.equal(e.kame_wasm_next_request_kind(hosted),1);
const header=e.kame_wasm_alloc(48,8);
assert.equal(e.kame_wasm_next_event_header(hosted,header,48),0);
const request=new DataView(e.memory.buffer).getBigUint64(header+20,true);
assert.notEqual(request,0n);
assert.equal(e.kame_wasm_event_payload_copy(hosted,output,4096),0);
assert.equal(e.kame_wasm_complete_bytes(hosted,request+1n,content.pointer,content.length),1);
assert.equal(e.kame_wasm_complete_bytes(hosted,request,content.pointer,content.length),0);
assert.equal(e.kame_wasm_complete_bytes(hosted,request,content.pointer,content.length),0);
for(let n=0;n<100;n++){const status=e.kame_wasm_step(hosted);if(status===2)break;assert.equal(status,0);assert(n<99,'hosted expression did not complete');}
assert.equal(e.kame_wasm_result_copy(hosted,output,4096,length),0);
assert.match(new TextDecoder().decode(new Uint8Array(e.memory.buffer,output,new DataView(e.memory.buffer).getUint32(length,true))), /backend bytes/);
assert.equal(e.kame_wasm_instance_free(hosted),0);
assert.equal(e.kame_wasm_free(header,48),0);
for(const b of [read,content])assert.equal(e.kame_wasm_free(b.pointer,b.allocated),0);
for(const b of [source,args,command])assert.equal(e.kame_wasm_free(b.pointer,b.allocated),0);
assert.equal(e.kame_wasm_free(output,4096),0);
assert.equal(e.kame_wasm_free(length,4),0);
assert.equal(e.kame_wasm_free(length,4),4);
console.log('Go WASM reactor: pure and hosted expressions, CLI, buffer bounds, and stale handles passed');
